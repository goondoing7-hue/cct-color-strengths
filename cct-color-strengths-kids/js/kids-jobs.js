function pickKidsJobs(ranked, n) {
  // TOP3 컬러마다 하나씩: 그 컬러가 대표인 직업 가운데, 함께 쓰는 컬러의 점수가 가장 높은 것
  const sc = {}; const rk = {};
  ranked.forEach((c, i) => { sc[c.key] = c.score || 0; rk[c.key] = i; });
  const bonus = (k) => (rk[k] < 3 ? 10 - rk[k] : 0) + (sc[k] || 0);
  return ranked.slice(0, n || 3).map((c) => {
    const cand = KIDS_JOBS.map((j, i) => ({ ...j, i })).filter((j) => j.c[0] === c.key);
    cand.sort((a, b) => bonus(b.c[1]) - bonus(a.c[1]) || a.i - b.i);
    return cand[0];
  }).filter(Boolean);
}

function kidsJobsForColor(key, n) {
  const prim = KIDS_JOBS.filter((j) => j.c[0] === key);
  const sec = KIDS_JOBS.filter((j) => j.c[1] === key);
  return prim.concat(sec).slice(0, n || 5);
}
